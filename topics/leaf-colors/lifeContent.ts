import { t } from './i18n.ts';
import { leafLifeAt } from './lifecycle.ts';
export function lifeContent(age: number) {
  const life = leafLifeAt(age);
  if (life.stage === 'bud') return {
    title: t('芽中幼叶，慢慢展开'),
    cause: t('幼叶逐渐生长、展开，仍连在原来的枝条位置。这里从芽中的叶开始，不是从一粒种子开始。'),
    story: t('记住这根枝条和这片卷着的幼叶。叶片展开后，面积增大，内部组织逐渐具备成熟叶的工作能力。形变是发育示意，不是细胞分裂模拟。'),
    observe: t('拖到成熟绿叶，再回头看：枝条的位置没有换，新长出的叶缘仍属于这片叶。'),
  };
  if (life.stage === 'mature') return {
    title: t('成熟的叶，正在工作'),
    cause: t('根供应水，叶脉运输；有光时，叶肉细胞利用光能制造糖。活细胞白天和夜晚也都能呼吸。'),
    story: t('叶子既与外界交换气体，也与植物其他部分交换物质。选“跟着水走”，看根、木质部与气孔；选“走进叶子里面”，观察同一处组织和色素。'),
    observe: t('把水的旅程停在叶内，再改变观察尺度：叶龄不会因此重新开始。'),
  };
  if (life.stage === 'senescent') return {
    title: t('衰老不是一层新油漆'),
    cause: t('日长、温度与植物自身状态影响衰老。光合作用装置逐渐拆解，一部分营养回到枝干和根；之后叶柄离层逐渐形成。'),
    story: t('绿色减弱后，原有黄色更容易看见；能变红的叶子还会积累花青素。黄色、红色是不同能力的对照，不是每片叶必经的两个阶段。'),
    observe: t('比较黄、红两路，再进入叶绿体与液泡。临近脱落时，叶柄与枝条的连接发生了什么？'),
  };
  return {
    title: t('同一片叶，离开枝条'),
    cause: t('离层使连接减弱，叶片脱离枝条。它不再从根获得这条连续水流；枝条上的脱落痕迹仍留在原处。'),
    story: t('这片叶没有消失，也不会变回下一年的幼叶。真实落叶随后会干燥、碎裂并被分解者利用；这些后续生态过程不在首版模拟中。'),
    observe: t('回退是重新观察教学状态，不是真实叶片逆转衰老。常绿植物也更新叶子，只是不都一起落叶。'),
  };
}
