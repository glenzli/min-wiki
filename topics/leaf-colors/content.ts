export function seasonStory(s: number, red: boolean, academic: boolean) {
  if (s < .28) return academic ? t('生长季中，叶绿素持续更新，绿色通常占主导；类胡萝卜素同时参与光能利用与光保护。') : t('夏天，叶绿素很多，绿色最显眼。黄色色素已经在叶子里，只是没有那么醒目。');
  if (s < .65) return academic ? t('日长变化、温度与植物自身发育共同影响叶片衰老。叶绿素分解加快，植物回收部分养分；变色不是简单地被冷空气染色。') : t('白天变短、天气变化，许多落叶植物开始为休眠做准备。叶绿素逐渐分解，树也从叶子里收回一部分养分。');
  if (red) return academic ? t('在能合成较多花青素的叶片中，花青素在衰老期间积累于液泡，叠加剩余色素形成红色或紫红色。具体色调受物种、光照、糖分与液泡环境等影响。') : t('这类叶子还会制造红色的花青素。放大到细胞里，看液泡变红；叶绿体里的绿色则继续减少。');
  return academic ? t('叶绿素减少后，保留下来的类胡萝卜素使叶片呈黄至橙色。类胡萝卜素也可能减少；黄色显现不等于它的数量一定增加。') : t('绿色退去，原本就在的黄色显现出来。这类叶子没有积累很多红色色素，于是秋天主要变成黄色。');
}

